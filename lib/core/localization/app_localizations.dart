    switch (module) {
      case NotificationModule.messages:
        return t('module.messages');
      case NotificationModule.orders:
        return t('module.orders');
      case NotificationModule.food:
        return t('module.food');
      case NotificationModule.shopping:
        return t('module.shopping');
      case NotificationModule.grocery:
        return t('module.grocery');
      case NotificationModule.pharmacy:
        return t('module.pharmacy');
      case NotificationModule.ride:
        return t('module.ride');
      case NotificationModule.hotel:
        return t('module.hotel');
      case NotificationModule.doctor:
        return t('module.doctor');
      case NotificationModule.homeServices:
        return t('module.home_services');
      case NotificationModule.laundry:
        return t('module.laundry');
      case NotificationModule.promotions:
        return t('module.promotions');
      case NotificationModule.account:
        return t('module.account');
      case NotificationModule.system:
        return t('module.system');
    }
  }

  String homeServiceDynamicLabel(String value) {
    final normalized = value
        .toLowerCase()
        .replaceAll('&', ' and ')
        .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
        .trim()
        .replaceAll(RegExp(r'\s+'), ' ');
    switch (languageCode) {
      case 'fr':
        return _homeServiceDynamicLabelsFr[normalized] ?? value;
      case 'ar':
        return _homeServiceDynamicLabelsAr[normalized] ?? value;
      default:
        return value;
    }
  }

  String homeServiceCategoryName(String slug, String fallback) {
    final key = slug.toLowerCase().replaceAll('_', '-').trim();
    switch (languageCode) {
      case 'fr':
        return _homeServiceCategoryNamesFr[key] ??
            homeServiceDynamicLabel(fallback);
      case 'ar':
        return _homeServiceCategoryNamesAr[key] ??
            homeServiceDynamicLabel(fallback);
      default:
        return fallback;
    }
  }

  String homeServiceCategoryDescription(String slug, String fallback) {
    final key = slug.toLowerCase().replaceAll('_', '-').trim();
    switch (languageCode) {
      case 'fr':
        return _homeServiceCategoryDescriptionsFr[key] ?? fallback;
      case 'ar':
        return _homeServiceCategoryDescriptionsAr[key] ?? fallback;
      default:
        return fallback;
    }
  }

  String homeServiceProviderSubtitle({
    String? categorySlug,
    String? categoryName,
    required String fallbackTitle,
  }) {
    if (languageCode == 'en') return fallbackTitle;
    final translatedTitle = homeServiceDynamicLabel(fallbackTitle);
    if (translatedTitle != fallbackTitle) return translatedTitle;
    final rawCategoryName = (categoryName ?? '').trim();
    final translatedCategory = homeServiceCategoryName(
      categorySlug ?? '',
      rawCategoryName,
    );
    if (translatedCategory.isNotEmpty) return translatedCategory;
    return fallbackTitle;
  }

