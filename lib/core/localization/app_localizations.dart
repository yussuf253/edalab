  static const supportedLocales = [Locale('en'), Locale('fr'), Locale('ar')];

  static const delegate = _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    final localization = Localizations.of<AppLocalizations>(
      context,
      AppLocalizations,
    );
    assert(localization != null, 'AppLocalizations not found in context');
    return localization!;
  }

  String get languageCode {
    final code = locale.languageCode.toLowerCase();
    final isSupported = supportedLocales.any(
      (item) => item.languageCode == code,
    );
    return isSupported ? code : fallbackLocale.languageCode;
  }

  String t(String key, {Map<String, String> params = const {}}) {
    final value =
        _localizedValues[languageCode]?[key] ??
        _localizedValues[fallbackLocale.languageCode]?[key] ??
        key;

    var output = value;
    for (final entry in params.entries) {
      output = output.replaceAll('{${entry.key}}', entry.value);
    }
    return output;
  }

