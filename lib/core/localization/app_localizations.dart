class AppLocalizations {
  AppLocalizations(this.locale);

  final Locale locale;

  static const fallbackLocale = Locale('en');
  static const supportedLocales = [Locale('en'), Locale('fr'), Locale('ar')];

  static const delegate = _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    final localization = Localizations.of<AppLocalizations>(
      context,
      AppLocalizations,
    );
    assert(localization != null, 'AppLocalizations not found in context');
    return localization!;
  }

  String get languageCode {
    final code = locale.languageCode.toLowerCase();
    final isSupported = supportedLocales.any(
      (item) => item.languageCode == code,
    );
    return isSupported ? code : fallbackLocale.languageCode;
  }

  String t(String key, {Map<String, String> params = const {}}) {
    final value =
        _localizedValues[languageCode]?[key] ??
        _localizedValues[fallbackLocale.languageCode]?[key] ??
        key;

    var output = value;
    for (final entry in params.entries) {
      output = output.replaceAll('{${entry.key}}', entry.value);
    }
    return output;
  }

  String moduleLabel(NotificationModule module) {
    switch (module) {
      case NotificationModule.messages:
        return t('module.messages');
      case NotificationModule.orders:
        return t('module.orders');
      case NotificationModule.food:
        return t('module.food');
      case NotificationModule.shopping:
        return t('module.shopping');
      case NotificationModule.grocery:
        return t('module.grocery');
      case NotificationModule.pharmacy:
        return t('module.pharmacy');
      case NotificationModule.ride:
        return t('module.ride');
      case NotificationModule.hotel:
        return t('module.hotel');
      case NotificationModule.doctor:
        return t('module.doctor');
      case NotificationModule.homeServices:
        return t('module.home_services');
      case NotificationModule.laundry:
        return t('module.laundry');
      case NotificationModule.promotions:
        return t('module.promotions');
      case NotificationModule.account:
        return t('module.account');
      case NotificationModule.system:
        return t('module.system');
    }
  }

